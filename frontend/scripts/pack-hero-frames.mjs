// Packs the BAT hero frames into a few files so the page makes ~35 requests instead of 557.
// Wix's Cloudflare answers 429 (and then blocks the whole site for that visitor) after ~160 quick requests.
// Each pack is the frames' AVIF files joined end to end, byte for byte: no re-encoding, same quality.
// Run from frontend/:  node scripts/pack-hero-frames.mjs
// Writes public/product/T-BAT/hero-frames/packs/*.bin and app/bat/components/batHeroFramePacks.ts.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { join } from "node:path"

const FRAMES_PER_PACK = 16
const src = "public/product/T-BAT/hero-frames/high"
const out = "public/product/T-BAT/hero-frames/packs"
const files = readdirSync(src).filter(f => /^bat-hero-\d{3}\.avif$/.test(f)).sort()
mkdirSync(out, { recursive: true })

const sizes = []
for (let p = 0; p * FRAMES_PER_PACK < files.length; p++) {
  const parts = files.slice(p * FRAMES_PER_PACK, (p + 1) * FRAMES_PER_PACK).map(f => readFileSync(join(src, f)))
  parts.forEach(b => sizes.push(b.length))
  writeFileSync(join(out, `bat-hero-pack-${String(p).padStart(2, "0")}.bin`), Buffer.concat(parts))
}

writeFileSync("app/bat/components/batHeroFramePacks.ts", `// Generated by scripts/pack-hero-frames.mjs from ${src} (${files.length} frames). Don't edit by hand.
// Frame i is in pack floor(i / FRAMES_PER_PACK); its bytes follow the earlier frames of that pack.
export const FRAMES_PER_PACK = ${FRAMES_PER_PACK}
export const FRAME_SIZES: number[] = [${sizes.join(",")}]
`)
console.log(`${files.length} frames -> ${Math.ceil(files.length / FRAMES_PER_PACK)} packs`)
