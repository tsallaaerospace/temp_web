"""Build source-coordinate foreground mattes for the BAT opening shot.
shortcut: colour key/rotor windows are calibrated to this edit; regenerate and inspect if footage changes.
"""
from pathlib import Path
from collections import deque
from PIL import Image, ImageFilter
import numpy as np
ROOT = Path(__file__).resolve().parents[1]
TRACK = [(0,945,543,1),(12,944.5,545,1.0273),(24,944.5,548,1.1061),(36,945,546,1.2),(48,945.5,548,1.2758),(60,942.5,553,1.2818),(64,945,537,1.303)]
def pose(i):
 for end,start in zip(TRACK[1:],TRACK):
  if i<=end[0]:
   t=(i-start[0])/(end[0]-start[0]);return [a+(b-a)*t for a,b in zip(start[1:],end[1:])]
 return TRACK[-1][1:]
def matte(i):
 im=Image.open(ROOT/'public/product/T-BAT/hero-frames/high'/f'bat-hero-{i+1:03}.avif').convert('RGB')
 x,y,size=pose(i);x0,y0,x1,y1=700,int(y)-3,1200,790
 a=np.array(im)[y0:y1,x0:x1].astype(float);r,g,b=a[:,:,0],a[:,:,1],a[:,:,2]
 m=(b>r-6)&(b>g-7)
 props=np.zeros(m.shape,bool)
 # Include the dark rotor blades/hubs only within their narrow windows above each wing.
 for hub in (877,1017):
  cx=x+(hub-945)*size-(3 if hub<945 else 7)*min(1,i/48)
  cy=y+27*size
  xx,yy=np.meshgrid(np.arange(x0,x1),np.arange(y0,y1))
  roi=(abs(xx-cx)<57*size)&(yy>cy-13*size)&(yy<cy+11*size)
  props |= roi&(r<112)&(b>r-28)
  m |= props
 seen=np.zeros(m.shape,bool);q=deque([(round(x)-x0,round(y)+15-y0)])
 while q:
  px,py=q.popleft()
  if px<0 or py<0 or py>=m.shape[0] or px>=m.shape[1] or seen[py,px] or not m[py,px]:continue
  seen[py,px]=True;q.extend(((px-1,py),(px+1,py),(px,py-1),(px,py+1)))
 # Close single-pixel compression holes; keep the edge inside the photographed silhouette.
 mask=Image.fromarray(((seen|props)*255).astype('uint8')).filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.MinFilter(3))
 return im,np.array(mask)>0,x0,y0
paths=[]
for i in range(61):
 im,m,x0,y0=matte(i);parts=[]
 for row,line in enumerate(m):
  edges=np.diff(np.r_[False,line,False].astype(int));starts=np.flatnonzero(edges==1);ends=np.flatnonzero(edges==-1)
  for start,end in zip(starts,ends):parts.append(f'M{start+x0} {row+y0}h{end-start}v1h{start-end}z')
 paths.append(''.join(parts))
 if i in (0,24,48,60,64):
  mask=Image.new('L',im.size);mask.paste(Image.fromarray((m*255).astype('uint8')),(x0,y0));im.paste('cyan',(0,0),mask);im.crop((700,510,1200,790)).save(ROOT.parent/f'.bat-matte-{i}.png')
import json
(ROOT/'app/bat/components/batHeroForeground.ts').write_text('// Generated by scripts/build-bat-foreground.py; source-frame mattes, never scaled with aircraft size.\nexport const BAT_FOREGROUND_PATHS = '+json.dumps(paths,separators=(',',':'))+' as const\n',encoding='utf-8')
print('Built',len(paths),'foreground paths;',sum(map(len,paths)),'path bytes')
